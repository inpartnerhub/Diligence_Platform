#!/usr/bin/env bash
# Entry point of the single-container demo (deploy/huggingface). Generates fresh credentials for this run, initialises
# PostgreSQL and hands over to supervisord, which starts every service and then setup.sh (users and demo data).
#   start.sh                          start the demo
#   start.sh after HOST:PORT... -- CMD   wait until every port accepts connections, then exec CMD (used by supervisord)
set -euo pipefail

if [ "${1:-}" = "after" ]; then
  shift
  while [ "$1" != "--" ]; do
    host=${1%:*} port=${1##*:}
    until (exec 3<>"/dev/tcp/$host/$port") 2> /dev/null; do sleep 2; done
    shift
  done
  shift
  exec "$@"
fi

# The public demo stays closed without a gate password (Space secret DEMO_GATE_PASSWORD, at least 8 characters).
gate=${DEMO_GATE_PASSWORD:-}
if [ "${#gate}" -lt 8 ]; then
  echo "DEMO_GATE_PASSWORD is not set (at least 8 characters). Add it as a secret in the Space settings." >&2
  exit 1
fi

mkdir -p /data/home /data/run /data/redis /data/s3 /data/opensearch /data/opensearch-logs \
  /data/rabbitmq/mnesia /data/rabbitmq/log /data/keycloak

rand() { openssl rand -hex 24; }
if [ ! -f /data/.env ]; then
  # Hugging Face provides SPACE_HOST (e.g. owner-space.hf.space); locally the demo runs on http://localhost:7860.
  app_base_url=${APP_BASE_URL:-${SPACE_HOST:+https://$SPACE_HOST}}
  cat > /data/.env << EOF
# Generated by deploy/huggingface/start.sh for this container run only.
APP_BASE_URL=${app_base_url:-http://localhost:7860}
POSTGRES_DB=diligence
POSTGRES_USER=diligence
POSTGRES_PASSWORD=$(rand)
REDIS_PASSWORD=$(rand)
RABBITMQ_USERNAME=diligence
RABBITMQ_PASSWORD=$(rand)
S3_BUCKET=diligence-documents
S3_REGION=us-east-1
S3_ACCESS_KEY_ID=$(rand)
S3_SECRET_ACCESS_KEY=$(rand)
KEYCLOAK_ADMIN_USERNAME=admin
KEYCLOAK_ADMIN_PASSWORD=$(rand)
KEYCLOAK_ADMIN_CLIENT_SECRET=$(rand)
OIDC_CLIENT_SECRET=$(rand)
KEYCLOAK_DEV_ADMIN=local.admin
KEYCLOAK_DEV_ADMIN_PASSWORD=Admin-$(rand)
KEYCLOAK_DEV_PM=local.pm
KEYCLOAK_DEV_PM_PASSWORD=Pm-$(rand)
SESSION_SECRET=$(rand)$(rand)
SESSION_ENCRYPTION_KEY=$(openssl rand -base64 32)
WEBHOOK_KEY_ENCRYPTION_KEY=$(openssl rand -base64 32)
DEMO_MODE=true
DEMO_PASSWORD=Demo-$(rand)
DEMO_TOTP_SECRET=$(python3 -c 'import base64,os;print(base64.b32encode(os.urandom(20)).decode())')
BACKEND_PORT=8080
EOF
  chmod 600 /data/.env
fi
set -a; source /data/.env; set +a

if [ ! -f /data/pg/PG_VERSION ]; then
  pwfile=$(mktemp); printf '%s' "$POSTGRES_PASSWORD" > "$pwfile"
  initdb -D /data/pg -U "$POSTGRES_USER" --pwfile="$pwfile" --auth-host=scram-sha-256 --auth-local=trust \
    --encoding=UTF8 --locale=C.UTF-8 > /dev/null
  rm -f "$pwfile"
  pg_ctl -D /data/pg -o "-c listen_addresses='' -k /data/run" -w start > /dev/null
  createdb -h /data/run -U "$POSTGRES_USER" "$POSTGRES_DB"
  pg_ctl -D /data/pg -m fast -w stop > /dev/null
fi

printf '{"identities":[{"name":"diligence","credentials":[{"accessKey":"%s","secretKey":"%s"}],"actions":["Admin","Read","Write","List","Tagging"]}]}' \
  "$S3_ACCESS_KEY_ID" "$S3_SECRET_ACCESS_KEY" > /data/s3.json
cat > /data/rabbitmq/rabbitmq.conf << EOF
listeners.tcp.default = 127.0.0.1:5672
default_user = $RABBITMQ_USERNAME
default_pass = $RABBITMQ_PASSWORD
loopback_users = none
EOF
chmod 600 /data/s3.json /data/rabbitmq/rabbitmq.conf

exec supervisord -n -c /etc/supervisor/demo.conf
